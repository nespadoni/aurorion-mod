def spell_icon(name, palette, rows):
    frame, field, strong, soft = palette
    image = Image.new("RGBA", (16, 16), frame + (255,))
    for y in range(14):
        line = (rows[y] + " " * 14)[:14]
        for x in range(14):
            char = line[x]
            color = strong if char == "*" else soft if char == "#" else field
            image.putpixel((x + 1, y + 1), color + (255,))
    image.save(SPELLS / f"{name}.png")
    return SPELLS / f"{name}.png"


def effect_icon(name, strong, soft, rows):
    image = Image.new("RGBA", (18, 18), (0, 0, 0, 0))
    for y in range(18):
        line = (rows[y] + "." * 18)[:18]
        for x in range(18):
            char = line[x]
            if char == "*":
                image.putpixel((x, y), strong + (255,))
            elif char == "#":
                image.putpixel((x, y), soft + (255,))
    image.save(EFFECTS / f"{name}.png")
    return EFFECTS / f"{name}.png"


